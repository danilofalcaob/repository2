export type Faixa = { min?: number; max?: number };

// Nome da alteração no resumo evolutivo. O gênero concorda o adjetivo
// ("leucocitose progressiva" / "alargamento progressivo do INR").
export type Sindrome = { nome: string; genero: "f" | "m" };

export type Analito = {
  codigo: string;
  nome: string; // nome por extenso (telas)
  rotulo: string; // como aparece na linha de exames
  grupo: Grupo;
  unidade: string; // unidade canônica (gráficos e tendências)
  casas: number; // casas decimais padrão
  ref?: Faixa; // referência adulta padrão (sexo indiferente)
  refF?: Faixa;
  refM?: Faixa;
  critico?: Faixa; // fora desta faixa = valor crítico (na unidade canônica)
  sinonimos: string[]; // nomes normalizados (minúsculas, sem acento)
  curtos?: string[]; // siglas curtas: só reconhecidas no início da linha
  // Fatores para converter a unidade informada na unidade canônica
  // (chave = unidade normalizada por chaveUnidade()).
  conversoes?: Record<string, number>;
  alto?: Sindrome;
  baixo?: Sindrome;
  delta?: number; // variação absoluta considerada relevante
  deltaRel?: number; // variação relativa considerada relevante (0,15 = 15%)
  resumo?: boolean; // false = não entra no resumo evolutivo
};

const f = (nome: string): Sindrome => ({ nome, genero: "f" });
const m = (nome: string): Sindrome => ({ nome, genero: "m" });

